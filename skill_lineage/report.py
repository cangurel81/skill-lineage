"""Human-readable Markdown rendering for lineage analysis."""

from __future__ import annotations

from typing import Any, Dict, List, Sequence

from . import __version__


def _section(lines: List[str], title: str, groups: Sequence[Dict[str, Any]]) -> None:
    lines.append("## %s (%d)" % (title, len(groups)))
    lines.append("")
    if not groups:
        lines.append("None.")
        lines.append("")
        return
    for group in groups:
        lines.append("### `%s`" % group["key"])
        lines.append("")
        lines.append("- Keep: `%s` (%s)" % (group["canonical"], group["canonical_reason"]))
        for candidate in group["candidates"]:
            lines.append("- Candidate: `%s`" % candidate)
        lines.append("")


def render_markdown(analysis: Dict[str, Any], roots: Sequence[str]) -> str:
    summary = analysis["summary"]
    lines = [
        "# skill-lineage report",
        "",
        "Generated by skill-lineage %s. Review every candidate before deleting." % __version__,
        "",
        "Roots:",
        "",
    ]
    for root in roots:
        lines.append("- `%s`" % root)
    lines.extend(
        [
            "",
            "## Summary",
            "",
            "| Metric | Count |",
            "|---|---:|",
            "| Skills scanned | %d |" % summary["skills"],
            "| Exact duplicate groups | %d |" % summary["exact_groups"],
            "| Exact copies | %d |" % summary["exact_copies"],
            "| Normalized duplicate groups | %d |" % summary["normalized_groups"],
            "| Normalized copies | %d |" % summary["normalized_copies"],
            "| Name conflicts | %d |" % summary["name_conflicts"],
            "| Name variants | %d |" % summary["name_variants"],
            "| Removal candidates | %d |" % summary["remove_candidates"],
            "",
        ]
    )
    _section(lines, "Exact duplicates", analysis["exact"])
    _section(lines, "Normalized duplicates", analysis["normalized"])
    _section(lines, "Name variants", analysis["variants"])
    _section(lines, "Name conflicts", analysis["conflicts"])
    lines.append("The plan is advisory only; this tool never deletes files.")
    lines.append("")
    return "\n".join(lines)
